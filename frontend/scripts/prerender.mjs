// Post-build step: writes one static HTML file per route with that page's
// <title>, description, canonical and Open Graph / Twitter tags, then
// generates sitemap.xml and robots.txt from the same route list.
//
// Why: this is a client-rendered SPA, and link-preview bots (LinkedIn,
// WhatsApp, Slack…) read raw HTML without running JavaScript. Without this,
// every shared link would show the home page's card. The page body is still
// rendered by React in the browser.
//
// Output is dist/<route>.html (e.g. dist/products/siem.html). Vercel serves
// it at /products/siem via `cleanUrls` in vercel.json; GitHub Pages and
// Netlify resolve extensionless URLs to .html on their own.
//
// Metadata comes from src/seo/pageMeta.ts (via src/seo/routes.ts), loaded
// through Vite so the TypeScript data files work as-is.
import { mkdir, readFile, writeFile } from 'node:fs/promises'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { createServer } from 'vite'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const dist = join(root, 'dist')

const vite = await createServer({
  root,
  mode: 'production',
  logLevel: 'error',
  server: { middlewareMode: true, hmr: false },
  appType: 'custom',
})
let routes, SITE_URL, DEFAULT_SITE_URL
try {
  ;({ prerenderRoutes: routes } = await vite.ssrLoadModule('/src/seo/routes.ts'))
  ;({ SITE_URL, DEFAULT_SITE_URL } = await vite.ssrLoadModule('/src/seo/siteUrl.ts'))
  routes = routes()
} finally {
  await vite.close()
}

const escapeHtml = (s) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;')

function setMeta(html, attr, key, value) {
  const re = new RegExp(`(<meta\\s+${attr}="${key}"\\s+content=")[^"]*(")`)
  if (!re.test(html)) throw new Error(`index.html is missing <meta ${attr}="${key}">`)
  return html.replace(re, `$1${escapeHtml(value)}$2`)
}

const template = (await readFile(join(dist, 'index.html'), 'utf8')).replaceAll(DEFAULT_SITE_URL, SITE_URL)

for (const route of routes) {
  const url = `${SITE_URL}${route.path === '/' ? '/' : route.path}`
  let html = template.replace(/<title>[^<]*<\/title>/, `<title>${escapeHtml(route.title)}</title>`)
  html = setMeta(html, 'name', 'description', route.description)
  html = setMeta(html, 'property', 'og:title', route.title)
  html = setMeta(html, 'property', 'og:description', route.description)
  html = setMeta(html, 'property', 'og:url', url)
  html = setMeta(html, 'name', 'twitter:title', route.title)
  html = setMeta(html, 'name', 'twitter:description', route.description)

  if (route.path === '/') {
    // index.html is also the SPA fallback for unknown URLs, so it carries no
    // canonical; usePageSeo adds the right one at runtime.
    await writeFile(join(dist, 'index.html'), html)
  } else {
    html = html.replace('</head>', `    <link rel="canonical" href="${escapeHtml(url)}" />\n  </head>`)
    const file = join(dist, `${route.path.slice(1)}.html`)
    await mkdir(dirname(file), { recursive: true })
    await writeFile(file, html)
  }
}

const sitemap = `<?xml version="1.0" encoding="UTF-8"?>
<!-- Generated by scripts/prerender.mjs from src/seo/routes.ts. -->
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
${routes
  .filter((r) => r.sitemap)
  .map((r) => `  <url><loc>${escapeHtml(`${SITE_URL}${r.path}`)}</loc></url>`)
  .join('\n')}
</urlset>
`
await writeFile(join(dist, 'sitemap.xml'), sitemap)
await writeFile(join(dist, 'robots.txt'), `User-agent: *\nAllow: /\n\nSitemap: ${SITE_URL}/sitemap.xml\n`)

console.log(`prerender: ${routes.length} routes, sitemap and robots.txt written for ${SITE_URL}`)
